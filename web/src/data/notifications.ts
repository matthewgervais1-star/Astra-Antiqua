/** Day-of-year in the local calendar, 1-366. */
function dayOfYear(date: Date): number {
  const start = new Date(date.getFullYear(), 0, 1);
  const diffMs =
    new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime() - start.getTime();
  return Math.floor(diffMs / (24 * 60 * 60 * 1000)) + 1;
}

/**
 * A deterministic notification line for a given culture and date: the same
 * day always yields the same line, and the line rotates day to day rather
 * than repeating a fixed weekly pattern.
 */
export function notificationForDate(culture: Culture, date: Date): string {
  const lines = NOTIFICATION_LINES[culture];
  const index = dayOfYear(date) % lines.length;
  return lines[index] ?? lines[0]!;
}
