/**
 * Exports the tier-2 culture emblems from docs/design/system/assets/marks into
 * web/src/marks, so the app can render a mark without reading an SVG at
 * runtime.
 *
 *   cd web && npm run export:marks
 *
 * docs/design/culture-marks.md sets out three tiers. Tier 2 is the in-app
 * emblem, "the marks each culture is known by", and it belongs where a label
 * stands beside it: culture doorways, section heads, share cards, chapter
 * marks. This script carries exactly the five the tier-2 table names, and it
 * carries them unedited: every path is the designer's and every one paints in
 * currentColor, so a culture accent is a colour rather than a second file.
 *
 * The generated module is never hand-edited. Rerun this after changing a mark.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const MARKS = path.join(SCRIPT_DIR, "..", "..", "docs", "design", "system", "assets", "marks");
const OUT_DIR = path.join(SCRIPT_DIR, "..", "src", "marks");

/**
 * The tier-2 emblem per culture, from docs/design/culture-marks.md. Canaan has
 * no popular emblem, which the research states plainly rather than papering
 * over, so its cuneiform carries both tiers. Carthage takes the header cut
 * with the solid disc and upturned arms, never the launcher outline.
 */
const EMBLEMS = [
  { culture: "egypt", file: "em-wedjat.svg", name: "The wedjat" },
  { culture: "greece", file: "em-owl.svg", name: "Athena's owl" },
  { culture: "canaan", file: "ts-il.svg", name: "The name of El in Ugaritic" },
  { culture: "carthage", file: "em-tanit-hdr.svg", name: "The sign of Tanit" },
  { culture: "rome", file: "em-aquila.svg", name: "The aquila" },
];

/** Only these elements, the same set the glyphs and marks are drawn with. */
const ALLOWED = new Set(["g", "path", "circle", "ellipse", "line", "polyline", "polygon", "rect"]);

function assert(condition, message) {
  if (!condition) throw new Error(`export-marks: ${message}`);
}

const records = [];
for (const { culture, file, name } of EMBLEMS) {
  const source = path.join(MARKS, file);
  assert(fs.existsSync(source), `${file} is missing from docs/design/system/assets/marks`);
  const text = fs.readFileSync(source, "utf8");

  const open = text.match(/<svg\b([^>]*)>/);
  assert(open, `${file} is not an SVG document`);
  const viewBox = open[1].match(/viewBox="([^"]+)"/);
  assert(viewBox, `${file} has no viewBox`);
  assert(viewBox[1].trim() === "0 0 512 512", `${file} is not on the 512 grid, it is "${viewBox[1]}"`);

  const close = text.lastIndexOf("</svg>");
  const inner = text
    .slice(open.index + open[0].length, close)
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .trim();

  for (const [, tag] of inner.matchAll(/<([a-zA-Z][\w-]*)/g)) {
    assert(ALLOWED.has(tag), `${file} uses <${tag}>, which these assets are not drawn with`);
  }
  assert(inner.includes("currentColor"), `${file} does not paint in currentColor`);
  assert(!/#[0-9A-Fa-f]{3,6}\b/.test(inner), `${file} carries a literal colour, so it cannot take an accent`);
  assert(!inner.includes("url("), `${file} references an external paint`);

  records.push({ culture, name, inner });
}

assert(records.length === 5, `expected 5 emblems, got ${records.length}`);

const body = records
  .map(
    (r) => `  ${r.culture}: {
    name: ${JSON.stringify(r.name)},
    inner: ${JSON.stringify(r.inner)},
  },`,
  )
  .join("\n");

const generated = `/**
 * GENERATED by scripts/export-marks.mjs from docs/design/system/assets/marks.
 * Do not edit; run \`npm run export:marks\`.
 *
 * The tier-2 emblem per culture, the mark each culture is known by
 * (docs/design/culture-marks.md). Each paints in currentColor on a 512 grid,
 * so the culture accent is a colour rather than a second file.
 */
import type { Culture } from "@/data/cultures";

export interface EmblemRecord {
  /** What the mark is, for the accessible name. */
  readonly name: string;
  /** The SVG's child markup, on a 0 0 512 512 viewBox. */
  readonly inner: string;
}

export const CULTURE_EMBLEMS: Readonly<Record<Culture, EmblemRecord>> = {
${body}
};
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
const target = path.join(OUT_DIR, "index.ts");
const tmp = `${target}.tmp`;
fs.writeFileSync(tmp, generated, "utf8");
fs.renameSync(tmp, target);

console.log(
  `export-marks: wrote src/marks/index.ts (${records.length} emblems: ` +
    `${records.map((r) => `${r.culture} ${r.name}`).join(", ")})`,
);
