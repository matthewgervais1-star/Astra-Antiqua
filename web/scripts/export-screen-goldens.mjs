/**
 * Builds every screen model (web/src/lib/screens) over the plan's fixed cases
 * and writes the printed text of every slot, one file per screen, for the
 * ports' golden tests:
 *
 *   cd web && pnpm export:screen-goldens
 *   -> shared/goldens/screens/<screen>.json
 *
 * Each case names its culture, instant, zone and birth record. The script
 * sets process.env.TZ to the case's zone before it builds the case (TZ= from
 * Git Bash does not take, android-glass.md line 399), and fails if the
 * runtime's local offset at the case's instant is not the zone's, because the
 * composition code counts local days with Date's local getters. Output is
 * NFC text with keys in the table's order, so two runs write the same bytes.
 * Writes atomically.
 * ASTRA_SHARED_OUT points it at another shared/ root (check-shared.mjs).
 */
process.env.TZ = "UTC";

import { register } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

register("./resolve-at-alias.mjs", import.meta.url);

const { SCREEN_BUILDERS } = await import("../src/lib/screens/index.ts");
const { SCREEN_SLOTS } = await import("../src/lib/screens/slots.ts");
const { GOLDEN_CASES, SMOKE_BIRTH, caseId, smokeNatal } = await import("../src/lib/screens/cases.ts");

const SHARED = process.env.ASTRA_SHARED_OUT ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../shared");
const OUT = path.join(SHARED, "goldens", "screens");

function fail(message) {
  throw new Error(`export-screen-goldens: ${message}`);
}

/** The zone's offset from UTC at `date`, in minutes east, read through Intl. */
function offsetIn(zone, date) {
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat("en-US", {
      timeZone: zone,
      hourCycle: "h23",
      year: "numeric",
      month: "numeric",
      day: "numeric",
      hour: "numeric",
      minute: "numeric",
    })
      .formatToParts(date)
      .map((p) => [p.type, p.value]),
  );
  const wall = Date.UTC(+parts.year, +parts.month - 1, +parts.day, +parts.hour % 24, +parts.minute);
  return Math.round((wall - Math.floor(date.getTime() / 60000) * 60000) / 60000);
}

function nfc(value, where) {
  const list = Array.isArray(value) ? value : [value];
  for (const t of list) {
    if (typeof t !== "string") fail(`${where} is not text`);
    if (t !== t.normalize("NFC")) fail(`${where} is not NFC`);
  }
  return value;
}

const screens = Object.keys(SCREEN_BUILDERS);
const out = Object.fromEntries(screens.map((s) => [s, []]));

for (const c of GOLDEN_CASES) {
  process.env.TZ = c.zone;
  const at = new Date(c.instant);
  if (-at.getTimezoneOffset() !== offsetIn(c.zone, at)) fail(`TZ=${c.zone} did not take at ${c.instant}`);
  const input = { culture: c.culture, instant: new Date(c.instant), zone: c.zone, birth: c.birth ? smokeNatal() : null };
  for (const screen of screens) {
    const model = SCREEN_BUILDERS[screen](input);
    const id = caseId(screen, c);
    // Keys in the table's order, so the file reads like the table and never reorders.
    const slots = {};
    for (const key of SCREEN_SLOTS[screen]) if (key in model) slots[key] = nfc(model[key], `${id} ${key}`);
    for (const key of Object.keys(model)) if (!(key in slots)) fail(`${id} prints ${key}, which the table does not list`);
    out[screen].push({ id, culture: c.culture, instant: c.instant, zone: c.zone, birth: c.birth, slots });
  }
}
process.env.TZ = "UTC";

fs.mkdirSync(OUT, { recursive: true });
for (const screen of screens) {
  const file = path.join(OUT, `${screen}.json`);
  const doc = {
    screen,
    note: "Generated by web/scripts/export-screen-goldens.mjs from web/src/lib/screens. Never hand-edit.",
    births: { smoke: SMOKE_BIRTH },
    slots: SCREEN_SLOTS[screen],
    cases: out[screen],
  };
  const tmp = `${file}.tmp`;
  fs.writeFileSync(tmp, `${JSON.stringify(doc, null, 2)}\n`, "utf8");
  fs.renameSync(tmp, file);
}

console.log(`export-screen-goldens: wrote ${screens.length} screens x ${GOLDEN_CASES.length} cases to ${path.relative(process.cwd(), OUT) || OUT}`);
