/**
 * Generates Android's copy of the shared strings catalog and format data.
 *
 *   cd web && pnpm export:strings && pnpm gen:android-strings
 *
 * Reads shared/strings/en.json and shared/strings/formats.json (written by
 * export-strings.mjs from web/src/strings) and writes, under
 * android/app/src/main/java/com/astra/antiqua/domain/generated/:
 *
 *   SharedStrings.kt  one `const val` per culture-free key and one
 *                     Map<AncientCulture, String> per per-culture key, named
 *                     as the key in UPPER_SNAKE ("season.kicker" becomes
 *                     SEASON_KICKER), so a missing key fails the compile.
 *   SharedFormats.kt  data only: the month, weekday, count, ordinal, sign,
 *                     planet and tone word lists, the separators, and each
 *                     format's pattern, rule and zone rule.
 *
 * The JSON is the input, never the TS, so one pipeline runs TS to JSON to
 * Kotlin. Fails on two keys that map to one Kotlin name.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(SCRIPT_DIR, "..", "..");
const SHARED = path.join(REPO, "shared", "strings");
const OUT_DIR = path.join(REPO, "android", "app", "src", "main", "java", "com", "astra", "antiqua", "domain", "generated");

const CULTURES = ["egypt", "greece", "canaan", "carthage", "rome"];

const en = JSON.parse(fs.readFileSync(path.join(SHARED, "en.json"), "utf8"));
const formats = JSON.parse(fs.readFileSync(path.join(SHARED, "formats.json"), "utf8"));

/** A Kotlin string literal: quotes, backslashes, dollars and newlines escaped. */
function kt(s) {
  return `"${s
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("$", "\\$")
    .replaceAll("\n", "\\n")}"`;
}

/** "day.longTransit.meta" -> "DAY_LONG_TRANSIT_META". */
function constName(key) {
  return key
    .split(".")
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase())
    .join("_");
}

const HEADER = (what) => `package com.astra.antiqua.domain.generated

/*
 * GENERATED by web/scripts/gen-android-strings.mjs from ${what}.
 * Do not edit by hand: change web/src/strings, run \`pnpm export:strings\`,
 * then \`pnpm gen:android-strings\`.
 */
`;

// ---- SharedStrings.kt ------------------------------------------------------

const seen = new Map();
const lines = [];
for (const [key, value] of Object.entries(en)) {
  const name = constName(key);
  if (seen.has(name)) throw new Error(`gen-android-strings: ${key} and ${seen.get(name)} both become ${name}`);
  seen.set(name, key);
  lines.push(`    /** \`${key}\` */`);
  if (typeof value === "string") {
    lines.push(`    const val ${name}: String = ${kt(value)}`);
  } else {
    for (const c of CULTURES) {
      if (typeof value[c] !== "string") throw new Error(`gen-android-strings: ${key} has no ${c}`);
    }
    lines.push(`    val ${name}: Map<AncientCulture, String> = mapOf(`);
    for (const c of CULTURES) lines.push(`        AncientCulture.${c.toUpperCase()} to ${kt(value[c])},`);
    lines.push("    )");
  }
}

const stringsKt = `${HEADER("shared/strings/en.json")}
import com.astra.antiqua.model.AncientCulture

/**
 * The shared strings catalog, one entry per \`<screen>.<slot>\` key, in the case
 * the reader sees (no surface transforms it). \`{slot}\` marks a run-time fill;
 * [fill] replaces each one.
 */
object SharedStrings {
${lines.join("\n")}

    private val SLOT = Regex("""\\{([A-Za-z][A-Za-z0-9]*)\\}""")

    /** The template with each \`{slot}\` replaced from [slots]; a missing slot throws. */
    fun fill(template: String, slots: Map<String, String> = emptyMap()): String =
        SLOT.replace(template) { m ->
            slots[m.groupValues[1]] ?: error("SharedStrings: missing slot {\${m.groupValues[1]}} in \\"\$template\\"")
        }
}
`;

// ---- SharedFormats.kt -----------------------------------------------------

function list(name, values) {
  return `    val ${name}: List<String> = listOf(${values.map(kt).join(", ")})`;
}

function map(name, obj) {
  const rows = Object.entries(obj).map(([k, v]) => `        ${kt(k)} to ${kt(v)},`);
  return `    val ${name}: Map<String, String> = mapOf(\n${rows.join("\n")}\n    )`;
}

const w = formats.words;
const rules = formats.rules;
const formatsKt = `${HEADER("shared/strings/formats.json")}
/**
 * The format rules' data (F1 to F14 of the ruled table). Data only: the
 * formatter that reads it lives beside the screens, and its tests run over
 * shared/goldens/formats.json. Zone rule: ${formats.zoneRule}
 */
object SharedFormats {
${list("MONTH_ABBR", w.monthAbbr)}
${list("MONTH_FULL", w.monthFull)}
    /** Sunday first. */
${list("WEEKDAY_ABBR", w.weekdayAbbr)}
    /** Index = count; zero is NONE; above twelve prints digits. */
${list("COUNT_WORDS", w.countWords)}
    /** Index = number, lower; index 0 unused. */
${list("ORDINAL_WORDS", w.ordinalWords)}
    /** Keyed by the sign's English name ("Capricorn"). */
${map("SIGN_FULL", w.signFull)}
${map("SIGN_ABBR", w.signAbbr)}
${map("SIGN_PHRASES", w.signPhrases)}
    /** Keyed by the planet id ("mercury"). */
${map("PLANET_NAMES", w.planetNames)}
    /** Keyed by the aspect kind ("trine"). */
${map("TONE_WORDS", w.toneWords)}
${map("SPAN_TONE_WORDS", w.spanToneWords)}
    const val RETROGRADE_MARK: String = ${kt(w.retrogradeMark)}
    const val SEP: String = ${kt(formats.separators.dot)}
    const val ARROW: String = ${kt(formats.separators.arrow)}
    /** Format name to its pattern. */
${map("PATTERNS", Object.fromEntries(Object.entries(rules).map(([k, v]) => [k, v.pattern])))}
    /** Format name to its rule id in the table (F1 to F14). */
${map("RULES", Object.fromEntries(Object.entries(rules).map(([k, v]) => [k, v.rule])))}
    /** Format name to its zone rule: UTC, slot (the zone the slot names), or none. */
${map("ZONES", Object.fromEntries(Object.entries(rules).map(([k, v]) => [k, v.zone])))}
}
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "SharedStrings.kt"), stringsKt, "utf8");
fs.writeFileSync(path.join(OUT_DIR, "SharedFormats.kt"), formatsKt, "utf8");
console.log(
  `gen-android-strings: wrote SharedStrings.kt (${Object.keys(en).length} keys) and SharedFormats.kt to ${path.relative(REPO, OUT_DIR)}`,
);
