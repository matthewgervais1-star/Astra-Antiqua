/**
 * Generates the offline birthplace quick-pick for Android.
 *
 *   cd web && node scripts/gen-android-cities.mjs
 *
 * Reads web/src/data/cities.ts and writes the Kotlin equivalent. The list is
 * the instant, offline suggestion set both surfaces show before the reader
 * types; anything not on it is found by the geocoder, so any real place on
 * earth can still be entered.
 *
 * Android needed this more than web did. Its birth form had only the platform
 * Geocoder, which needs a network and a backend that is not always reachable,
 * so a reader offline could not finish the first run at all: there was no way
 * to name a birthplace and no way past the screen.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(SCRIPT_DIR, "..", "..");
const SRC = path.join(REPO, "web", "src");
const OUT = path.join(
  REPO, "android", "app", "src", "main", "java", "com", "astra", "antiqua", "data",
);

function fail(message) {
  throw new Error(`gen-android-cities: ${message}`);
}

const kotlinString = (s) =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

const source = await readFile(path.join(SRC, "data", "cities.ts"), "utf8");
const cities = [];
const pattern =
  /\{\s*name:\s*"([^"]*)",\s*country:\s*"([^"]*)",\s*latitude:\s*(-?[\d.]+),\s*longitude:\s*(-?[\d.]+)(,\s*popular:\s*(true|false))?\s*\}/g;
let match;
while ((match = pattern.exec(source)) !== null) {
  const [, name, country, latitude, longitude, , popular] = match;
  cities.push({
    name,
    country,
    latitude: Number(latitude),
    longitude: Number(longitude),
    popular: popular === "true",
  });
}
if (cities.length < 20) fail(`expected a real city list, found ${cities.length} entries`);

const file = `package com.astra.antiqua.data

/**
 * GENERATED by web/scripts/gen-android-cities.mjs from web/src/data/cities.ts.
 * Do not edit; run \`cd web && node scripts/gen-android-cities.mjs\`.
 *
 * The offline birthplace quick-pick: ${cities.length} modern cities, the same list
 * the web surface shows before the reader types. Anything not here is found
 * by the geocoder, so any real place on earth can still be entered.
 *
 * The list stays modern on purpose. Nobody is born in an archaeological site,
 * so the ancient ritual centres that belong to the pantheons live on the
 * doorways, not in a birthplace picker.
 */
data class CityEntry(
    val name: String,
    val country: String,
    val latitude: Double,
    val longitude: Double,
    /** Shown before the reader has typed anything. */
    val popular: Boolean,
)

object Cities {
    val ALL: List<CityEntry> = listOf(
${cities
  .map(
    (c) =>
      `        CityEntry(${kotlinString(c.name)}, ${kotlinString(c.country)}, ${c.latitude}, ${c.longitude}, ${c.popular}),`,
  )
  .join("\n")}
    )

    /** The defaults, for an empty field. */
    val POPULAR: List<CityEntry> = ALL.filter { it.popular }

    /**
     * Cities whose name or country contains [query], the leading matches
     * first. A name that STARTS with what was typed is what the reader
     * usually means, so those sort above a match in the middle of a word.
     */
    fun search(query: String, limit: Int = 8): List<CityEntry> {
        val needle = query.trim().lowercase()
        if (needle.isEmpty()) return POPULAR.take(limit)
        val starts = mutableListOf<CityEntry>()
        val contains = mutableListOf<CityEntry>()
        for (city in ALL) {
            val name = city.name.lowercase()
            when {
                name.startsWith(needle) -> starts += city
                name.contains(needle) || city.country.lowercase().contains(needle) ->
                    contains += city
            }
        }
        return (starts + contains).take(limit)
    }
}
`;

await mkdir(OUT, { recursive: true });
await writeFile(path.join(OUT, "Cities.kt"), file);
console.log(
  `gen-android-cities: wrote Cities.kt (${cities.length} cities, ` +
    `${cities.filter((c) => c.popular).length} popular)`,
);
