/**
 * Generates Android's copy of the script-reveal names.
 *
 *   cd web && node scripts/gen-android-script-forms.mjs
 *
 * Imports web/src/data/scriptForms.ts directly (Node's type stripping plus
 * the "@/" alias hook, as gen-android-reading-banks.mjs does) and writes
 * android/app/src/main/java/com/astra/antiqua/domain/ScriptForms.kt: for
 * every deity seat, the culture's name and its institution heading, the
 * attested script form (or null), the English form and the French form.
 * The sources and notes stay in the web file, which is canonical; Android
 * carries only what it draws. ScriptFormsParityTest pins a few entries per
 * culture by value, so a hand edit to the Kotlin shows up as a failure.
 */
import { register } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

register("./resolve-at-alias.mjs", import.meta.url);

const { DEITY_SCRIPT_FORMS, CULTURE_NAME_FORMS, INSTITUTION_FORMS } = await import("../src/data/scriptForms.ts");

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(SCRIPT_DIR, "..", "..");
const OUT = path.join(REPO, "android", "app", "src", "main", "java", "com", "astra", "antiqua", "domain", "ScriptForms.kt");

const CULTURES = ["egypt", "greece", "canaan", "carthage", "rome"];
const PLANETS = ["sun", "moon", "mercury", "venus", "mars", "jupiter", "saturn", "uranus", "neptune", "pluto"];

function fail(message) {
  throw new Error(`gen-android-script-forms: ${message}`);
}

const upper = (s) => s.toUpperCase();
const kt = (s) => {
  if (typeof s !== "string") fail(`expected a string, got ${JSON.stringify(s)}`);
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\n/g, "\\n")}"`;
};

function form(f, where) {
  if (!f) fail(`${where} is missing`);
  if (f.script !== null && typeof f.script !== "string") fail(`${where}.script is neither a string nor null`);
  const script = f.script === null || f.script.length === 0 ? "null" : kt(f.script);
  return `ScriptForm(${script}, ${kt(f.en)}, ${kt(f.fr)})`;
}

const deityArms = CULTURES.map((c) => {
  const inner = PLANETS.map(
    (p) => `            Planet.${upper(p)} -> ${form(DEITY_SCRIPT_FORMS[c]?.[p], `${c}.${p}`)}`,
  ).join("\n");
  return `        AncientCulture.${upper(c)} -> when (planet) {\n${inner}\n        }`;
}).join("\n");

const headingArms = (table, name) =>
  CULTURES.map((c) => `        AncientCulture.${upper(c)} -> ${form(table[c], `${name}.${c}`)}`).join("\n");

const file = `package com.astra.antiqua.domain

import com.astra.antiqua.model.AncientCulture
import com.astra.antiqua.model.Planet

/*
 * GENERATED by web/scripts/gen-android-script-forms.mjs from
 * web/src/data/scriptForms.ts. Do not edit by hand: change the web data and
 * re-run the generator. The sources for every script form live there.
 */

/**
 * One name in its culture's writing and in the reader's Latin.
 *
 * [script] is the attested spelling, or null when no spelling can be cited;
 * a null name shows Latin only. [en] is the name as the app prints it, [fr]
 * the established French scholarly form.
 */
data class ScriptForm(val script: String?, val en: String, val fr: String)

/** Every script-reveal name, keyed like web's DEITY_SCRIPT_FORMS, CULTURE_NAME_FORMS and INSTITUTION_FORMS. */
object ScriptForms {
    fun deity(culture: AncientCulture, planet: Planet): ScriptForm = when (culture) {
${deityArms}
    }

    /** The culture's own name (Kemet, Hellas, Qart-hadasht, Roma). */
    fun cultureName(culture: AncientCulture): ScriptForm = when (culture) {
${headingArms(CULTURE_NAME_FORMS, "CULTURE_NAME_FORMS")}
    }

    /** The institution heading, where a native word is attested. */
    fun institution(culture: AncientCulture): ScriptForm = when (culture) {
${headingArms(INSTITUTION_FORMS, "INSTITUTION_FORMS")}
    }
}
`;

await writeFile(OUT, file);
console.log(`wrote ${path.relative(REPO, OUT)}`);
