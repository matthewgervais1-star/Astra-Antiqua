/**
 * Generates Android's offline birthplace time-zone lookup.
 *
 *   cd web && node scripts/gen-android-tz.mjs
 *
 * Web resolves a birth's zone with the `tz-lookup` package (CC0-1.0), a
 * quadtree of IANA zone names packed into one string. This reads that
 * package's own `tz.js`, takes out the packed tree and the zone list, checks
 * that a JavaScript walk of the extracted data agrees with the package on a
 * grid of points, and writes them as Kotlin for `domain/BirthZone.kt`, which
 * walks the same tree. Both surfaces then name the same zone for the same
 * coordinates. Re-run after a `tz-lookup` upgrade.
 */
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(SCRIPT_DIR, "..", "..");
const OUT = path.join(
  REPO, "android", "app", "src", "main", "java", "com", "astra", "antiqua", "domain", "TzLookupData.kt",
);

function fail(message) {
  throw new Error(`gen-android-tz: ${message}`);
}

const require = createRequire(import.meta.url);
const tzlookup = require("tz-lookup");
const pkg = require("tz-lookup/package.json");
const source = await readFile(require.resolve("tz-lookup"), "utf8");

// The minified package opens with `var <data>="...",<list>=[...];`.
const match = /var \w="((?:[^"\\]|\\.)*)",\w=(\[[^\]]*\]);/.exec(source);
if (!match) fail("could not find the packed tree in tz-lookup/tz.js");
const data = JSON.parse(`"${match[1]}"`);
const list = JSON.parse(match[2]);
if (list.length === 0 || list.some((z) => typeof z !== "string")) fail("zone list is malformed");

/** The package's walk, over the extracted data; the Kotlin port mirrors it. */
function walk(lat, lon) {
  if (lat >= 90) return "Etc/GMT";
  let n = -1;
  let x = ((180 + lon) * 48) / 360.00000000000006;
  let y = ((90 - lat) * 24) / 180.00000000000003;
  let u = Math.trunc(x);
  let v = Math.trunc(y);
  let i = v * 96 + u * 2;
  i = data.charCodeAt(i) * 56 + data.charCodeAt(i + 1) - 1995;
  while (i + list.length < 3136) {
    n = n + i + 1;
    x = ((x - u) * 2) % 2;
    y = ((y - v) * 2) % 2;
    u = Math.trunc(x);
    v = Math.trunc(y);
    i = n * 8 + v * 4 + u * 2 + 2304;
    i = data.charCodeAt(i) * 56 + data.charCodeAt(i + 1) - 1995;
  }
  return list[i + list.length - 3136];
}

let checked = 0;
for (let lat = -89.75; lat < 90; lat += 0.5) {
  for (let lon = -179.75; lon < 180; lon += 0.5) {
    const expected = tzlookup(lat, lon);
    const actual = walk(lat, lon);
    if (expected !== actual) fail(`walk disagrees at ${lat},${lon}: ${actual} vs ${expected}`);
    checked += 1;
  }
}

const kotlinString = (s) =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

// A Kotlin string literal compiles to a class-file constant, capped at 65535
// bytes, so the tree goes out in chunks joined once at first use.
const CHUNK = 16000;
const chunks = [];
for (let at = 0; at < data.length; at += CHUNK) chunks.push(data.slice(at, at + CHUNK));

const file = `package com.astra.antiqua.domain

/**
 * GENERATED by web/scripts/gen-android-tz.mjs from tz-lookup ${pkg.version}
 * (CC0-1.0, the package web/src/lib/birthDateTime.ts uses).
 * Do not edit; run \`cd web && node scripts/gen-android-tz.mjs\`.
 *
 * The packed quadtree and the zone list that [birthZoneIdAt] walks.
 */
internal object TzLookupData {
    val TREE: String by lazy {
        listOf(
${chunks.map((c) => `            ${kotlinString(c)},`).join("\n")}
        ).joinToString("")
    }

    val ZONES: Array<String> = arrayOf(
${list.map((z) => `        ${kotlinString(z)},`).join("\n")}
    )
}
`;

await writeFile(OUT, file);
console.log(
  `gen-android-tz: wrote TzLookupData.kt (${data.length} tree chars, ${list.length} zones, ` +
    `${checked} points checked against tz-lookup ${pkg.version})`,
);
